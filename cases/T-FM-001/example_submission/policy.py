"""T-FM-001 reference submission, inference side: a flow-matching action head (Lipman et al. 2023; rectified-flow form,
Liu et al. 2023) over action chunks, conditioned on the current keypoint observation.

The velocity network is an MLP on [standardised observation (18), noisy chunk (16 x 2), sinusoidal time (32)]. A chunk
is generated by 10 Euler steps of dx/dt = v(x, t, o) from Gaussian noise at t = 0 to t = 1, then de-standardised; the
policy executes its first 8 actions open loop and replans. Noise comes from a generator seeded from ABENCH_SEED.
train.py fits the network (checkpoint/flow.pt with the standardisation statistics).
"""
from __future__ import annotations

import math
import os
from pathlib import Path

import numpy as np
import torch
import torch.nn as nn

HORIZON, EXECUTE, STEPS, HIDDEN = 16, 8, 10, 512
OBS_DIM, ACT_DIM, T_DIM = 18, 2, 32


def time_embedding(t: torch.Tensor) -> torch.Tensor:
    f = torch.exp(torch.arange(T_DIM // 2, device=t.device) * (-math.log(1000.0) / (T_DIM // 2 - 1)))
    a = t[:, None] * 1000.0 * f[None]
    return torch.cat([a.sin(), a.cos()], 1)


class Velocity(nn.Module):
    def __init__(self):
        super().__init__()
        d = OBS_DIM + HORIZON * ACT_DIM + T_DIM
        self.net = nn.Sequential(nn.Linear(d, HIDDEN), nn.SiLU(), nn.Linear(HIDDEN, HIDDEN), nn.SiLU(),
                                 nn.Linear(HIDDEN, HIDDEN), nn.SiLU(), nn.Linear(HIDDEN, HORIZON * ACT_DIM))

    def forward(self, x, t, o):
        return self.net(torch.cat([o, x.flatten(1), time_embedding(t)], 1)).view(-1, HORIZON, ACT_DIM)


def load(checkpoint_dir, device="cuda"):
    ck = torch.load(Path(checkpoint_dir) / "flow.pt", map_location="cpu", weights_only=True)
    net = Velocity()
    net.load_state_dict(ck["net"])
    stats = {k: ck[k].to(device) for k in ("obs_mu", "obs_sd", "act_mu", "act_sd")}
    g = torch.Generator(device=device)
    g.manual_seed(int(os.environ.get("ABENCH_SEED", "0")))
    return {"net": net.to(device).eval(), "device": device, "gen": g, **stats}


@torch.no_grad()
def sample_chunk(m, obs: np.ndarray) -> np.ndarray:
    dev = m["device"]
    o = (torch.as_tensor(obs, dtype=torch.float32, device=dev)[None] - m["obs_mu"]) / m["obs_sd"]
    x = torch.randn(1, HORIZON, ACT_DIM, generator=m["gen"], device=dev)
    for k in range(STEPS):
        t = torch.full((1,), k / STEPS, device=dev)
        x = x + m["net"](x, t, o) / STEPS
    return (x[0] * m["act_sd"] + m["act_mu"]).cpu().numpy()


class _Policy:
    def __init__(self, m):
        self.m, self.queue = m, []

    def reset(self):
        self.queue = []

    def act(self, obs):
        if not self.queue:
            chunk = sample_chunk(self.m, np.concatenate([obs["agent_pos"], obs["environment_state"]]))
            self.queue = list(chunk[:EXECUTE])
        return np.clip(self.queue.pop(0), 0, 512)


def make_policy(model):
    return _Policy(model)
