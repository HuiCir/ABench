"""X-GRPO-002: verifiable problems for RL post-training of Qwen2.5-0.5B-Instruct (Apache-2.0).

  Countdown  generated by harness/verify_math.make_countdown: public dev 500 instances from a public seed (agents can
             generate any number of training instances themselves); hidden 1,000 instances from the secret seed
             ABENCH_X_GRPO_SEED (instances identical to a dev instance are dropped)
  GSM8K      openai/gsm8k main (Cobbe et al. 2021, MIT): public = the training split, of which 300 problems are set
             aside as dev; hidden = the 1,319 test problems
"""
from __future__ import annotations

import importlib.util
import json
import os
import tempfile
from pathlib import Path

import numpy as np

from prepare.common import ROOT, Frozen, check

SECRET_SEED_ENV = "ABENCH_X_GRPO_SEED"
GSM_REV = "740312add88f781978c0658806c59bc2815b9866"
MODEL, MODEL_REV = "Qwen2.5-0.5B-Instruct", "7ae557604adf67be50417f59c2c2f167def9a775"
MODEL_FILES = ["config.json", "generation_config.json", "model.safetensors", "tokenizer.json", "tokenizer_config.json",
               "vocab.json", "merges.txt"]
SOURCES = [{"name": f"gsm8k/main/{s}-00000-of-00001.parquet",
            "url": f"https://huggingface.co/datasets/openai/gsm8k/resolve/{GSM_REV}/main/{s}-00000-of-00001.parquet",
            "license": "MIT", "note": f"RAW/gsm8k/main/{s}-00000-of-00001.parquet"} for s in ("train", "test")] + \
          [{"name": f"{MODEL}/", "url": f"https://huggingface.co/Qwen/{MODEL}/tree/{MODEL_REV}", "files": MODEL_FILES,
            "license": "Apache-2.0", "note": f"RAW/{MODEL}/"}]
N_DEV_CD, N_DEV_GSM, N_HELD_CD, DEV_SEED = 500, 300, 1000, 20240205


def _mods():
    h = ROOT / "cases" / "X-GRPO-002" / "harness"
    import sys
    sys.path.insert(0, str(h))
    sys.path.insert(0, str(ROOT / "tools" / "harness_kit"))
    out = []
    for name in ("verify_math", "stages"):
        spec = importlib.util.spec_from_file_location(f"xgrpo_{name}", h / f"{name}.py")
        m = importlib.util.module_from_spec(spec)
        spec.loader.exec_module(m)
        out.append(m)
    return out


def _freeze(train: list, test: list, seed: int, sums: dict) -> Frozen:
    V, S = _mods()
    dev_cd = V.make_countdown(np.random.default_rng(DEV_SEED), N_DEV_CD)
    seen = {json.dumps(c, sort_keys=True) for c in dev_cd}
    held_cd = [c for c in V.make_countdown(np.random.default_rng(seed), N_HELD_CD + 50)
               if json.dumps(c, sort_keys=True) not in seen][:N_HELD_CD]
    perm = np.random.default_rng(DEV_SEED).permutation(len(train))
    dev_gsm = [train[i] for i in perm[:N_DEV_GSM]]
    pub_train = [train[i] for i in perm[N_DEV_GSM:]]
    tmp = Path(tempfile.mkdtemp(prefix="xgrpo-"))
    (tmp / "gsm8k_train.json").write_text(json.dumps(pub_train))
    (tmp / "dev.json").write_text(json.dumps({"countdown": dev_cd, "gsm8k": dev_gsm}))
    held, ref = S.held_out_from(held_cd, test)
    return Frozen(public={}, hidden={**held, **ref}, sources_sha256=sums,
                  raw_files={"gsm8k_train.json": tmp / "gsm8k_train.json", "dev.json": tmp / "dev.json"},
                  notes={"countdown_held": len(held_cd), "gsm8k_test": len(test)})


def _gsm(p: Path) -> list:
    import pandas as pd                          # operator environment
    V, _ = _mods()
    df = pd.read_parquet(p)
    return [{"question": q, "solution": a, "gold": V.gsm8k_gold(a)} for q, a in zip(df["question"], df["answer"])]


def build(raw: Path) -> Frozen:
    seed = int(os.environ.get(SECRET_SEED_ENV, "0"))
    if not seed:
        raise SystemExit(f"set {SECRET_SEED_ENV} to a secret integer (held-out Countdown instances)")
    d = raw / "gsm8k" / "main"
    sums = {f: check(d / f) for f in ("train-00000-of-00001.parquet", "test-00000-of-00001.parquet")}
    train, test = _gsm(d / "train-00000-of-00001.parquet"), _gsm(d / "test-00000-of-00001.parquet")
    assert (len(train), len(test)) == (7473, 1319), (len(train), len(test))
    fz = _freeze(train, test, seed, sums)
    fz.models = {MODEL: raw / MODEL}
    return fz


def synthetic(n: int) -> Frozen:
    rng = np.random.default_rng(0)
    def item(i):
        a, b = int(rng.integers(2, 50)), int(rng.integers(2, 50))
        return {"question": f"Tom has {a} apples and buys {b} more. How many apples does he have?",
                "solution": f"{a}+{b}={a + b}\n#### {a + b}", "gold": str(a + b)}
    return _freeze([item(i) for i in range(max(n, 400))], [item(i) for i in range(n)], 12345, {"synthetic": f"n{n}"})
