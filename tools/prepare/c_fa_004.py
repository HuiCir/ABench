"""C-FA-004: held-out attention shapes for forward + backward (no download). The operator sets ABENCH_C_FA_SEED; shapes mix head dimensions
64/128, causal and non-causal, power-of-two and odd sequence lengths, with B·H·T² bounded so the fp32 reference fits."""
from __future__ import annotations

import os
from pathlib import Path

import numpy as np

from prepare.common import Frozen

SECRET_SEED_ENV = "ABENCH_C_FA_SEED"          # escrowed by tools/prepare/run.py next to the hidden-set key

SOURCES = [{"name": "held-out shape list", "generator": "tools/prepare/c_fa_004.py", "license": "generated by ABench"}]
GRID = [  # B, H, T, D, causal
    (8, 16, 512, 64, 1), (4, 16, 1024, 64, 0), (4, 16, 1024, 128, 1), (2, 32, 2048, 64, 1), (2, 16, 2048, 128, 0),
    (1, 16, 4096, 64, 1), (1, 16, 4096, 128, 1), (1, 8, 8192, 64, 1), (3, 12, 1000, 64, 1), (2, 20, 3001, 128, 0),
    (16, 8, 257, 64, 0), (1, 12, 6144, 128, 1),
]


def _shapes(seed: int) -> np.ndarray:
    rng = np.random.default_rng(seed)
    return np.array([[*g, int(rng.integers(1, 2**31 - 1))] for g in GRID], np.int64)


def build(raw: Path) -> Frozen:
    seed = int(os.environ.get("ABENCH_C_FA_SEED", "0"))
    if not seed:
        raise SystemExit("set ABENCH_C_FA_SEED to a secret integer (seeds of the random q, k, v)")
    return Frozen(public={}, hidden={"shapes": _shapes(seed)}, sources_sha256={"generator": "c_fa_004.py"})


def synthetic(n: int) -> Frozen:
    return Frozen(public={}, hidden={"shapes": _shapes(1)[:3]}, sources_sha256={"synthetic": "grid[:3]"})
