"""B-OPT-002: the B-OPT-001 data (FineWeb-10B GPT-2 token shards, kjj0/fineweb10B-gpt2, MIT) and a secret seed for
the gradient stream of the screen.

Public: train shards 1-2 verbatim (as B-OPT-001). Held out: the first 4,194,305 tokens of fineweb_val_000000.bin and
the screen seed (drawn from ABENCH_B_OPT2_SEED); the gradient stream itself is generated by harness/behaviour.stream.
"""
from __future__ import annotations

import os
from pathlib import Path

import numpy as np

from prepare import b_opt_001 as B
from prepare.common import Frozen

SOURCES = B.SOURCES
SECRET_SEED_ENV = "ABENCH_B_OPT2_SEED"


def _with_seed(fz: Frozen, seed: int) -> Frozen:
    stream_seed = int(np.random.default_rng(seed).integers(1_000, 2**31 - 1))
    fz.hidden = {**fz.hidden, "stream_seed": np.asarray([stream_seed], np.int64)}
    return fz


def build(raw: Path) -> Frozen:
    seed = int(os.environ.get(SECRET_SEED_ENV, "0"))
    if not seed:
        raise SystemExit(f"set {SECRET_SEED_ENV} to a secret integer (gradient stream)")
    return _with_seed(B.build(raw), seed)


def synthetic(n: int) -> Frozen:
    return _with_seed(B.synthetic(n), 12345)
