"""C-KV-002: RULER-style long-context prompts (cases/C-KV-002/harness/ruler_tasks.py) for Qwen2.5-1.5B-Instruct
(Qwen/Qwen2.5-1.5B-Instruct, Apache-2.0), tokenised with its chat template and the task's answer prefix appended to
the assistant turn, each as close as possible to (and not longer than) 4,096, 8,192 or 16,384 tokens.
Held out: 12 prompts per task and length from a secret seed; public dev set: 3 per task and length from seed 1."""
from __future__ import annotations

import importlib.util
import os
import sys
from pathlib import Path

import numpy as np

from prepare.common import Frozen, check

HARNESS = Path(__file__).resolve().parents[2] / "cases" / "C-KV-002" / "harness"
MODEL, REV = "Qwen2.5-1.5B-Instruct", "989aa7980e4cf806f80c7fef2b1adb7bc71aa306"
MODEL_FILES = ["config.json", "generation_config.json", "model.safetensors", "tokenizer.json", "tokenizer_config.json",
               "vocab.json", "merges.txt"]
SOURCES = [{"name": f"{MODEL}/", "url": f"https://huggingface.co/Qwen/{MODEL}/tree/{REV}", "files": MODEL_FILES,
            "license": "Apache-2.0"},
           {"name": "RULER-style tasks", "generator": "cases/C-KV-002/harness/ruler_tasks.py", "license": "generated by ABench"}]
SECRET_SEED_ENV = "ABENCH_C_KV_SEED"          # escrowed by tools/prepare/run.py next to the hidden-set key
LENGTHS, N_HELD, N_DEV = (4096, 8192, 16384), 12, 3


def _tasks():
    sys.path.insert(0, str(HARNESS))
    spec = importlib.util.spec_from_file_location("ruler_tasks", HARNESS / "ruler_tasks.py")
    mod = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(mod)
    return mod


def encode(tok, prompt: str, prefix: str) -> list[int]:
    ids = tok.apply_chat_template([{"role": "user", "content": prompt}], add_generation_prompt=True)
    return list(ids) + tok(" " + prefix, add_special_tokens=False)["input_ids"]


def make_set(tok, seed: int, n: int) -> dict:
    R = _tasks()
    rng = np.random.default_rng(seed)
    seqs, tasks, lengths, expected = [], [], [], []
    for task in R.TASKS:
        for L in LENGTHS:
            for _ in range(n):
                lo, hi = 8, L // 4                       # noise repetitions: binary search for the longest that fits
                best = None
                state = rng.bit_generator.state
                while lo <= hi:
                    mid = (lo + hi) // 2
                    rng.bit_generator.state = state
                    p, a, e = R.make(task, mid, rng)
                    ids = encode(tok, p, a)
                    if len(ids) <= L:
                        best, lo = (ids, e), mid + 1
                    else:
                        hi = mid - 1
                ids, e = best
                assert L - len(ids) < 200, (task, L, len(ids))
                seqs.append(np.asarray(ids, np.int32)); tasks.append(task); lengths.append(L); expected.append("|".join(e))
    off = np.concatenate([[0], np.cumsum([len(s) for s in seqs])]).astype(np.int64)
    return {"tokens": np.concatenate(seqs), "offsets": off, "task": np.asarray(tasks), "length": np.asarray(lengths),
            "expected": np.asarray(expected)}


def build(raw: Path) -> Frozen:
    from transformers import AutoTokenizer           # operator environment only
    seed = int(os.environ.get(SECRET_SEED_ENV, "0"))
    if not seed:
        raise SystemExit(f"set {SECRET_SEED_ENV} to a secret integer (the held-out prompts)")
    sums = {f"{MODEL}/{f}": check(raw / MODEL / f) for f in MODEL_FILES}
    tok = AutoTokenizer.from_pretrained(str(raw / MODEL), local_files_only=True)
    return Frozen(public={"dev_prompts.npz": make_set(tok, 1, N_DEV)}, hidden=make_set(tok, seed, N_HELD),
                  sources_sha256=sums, models={MODEL: raw / MODEL})


def synthetic(n: int) -> Frozen:
    rng = np.random.default_rng(0)
    R = _tasks()

    def fake(k):
        seqs = [rng.integers(0, 1000, 50).astype(np.int32) for _ in range(k * len(R.TASKS))]
        off = np.concatenate([[0], np.cumsum([len(s) for s in seqs])]).astype(np.int64)
        return {"tokens": np.concatenate(seqs), "offsets": off, "task": np.repeat(np.asarray(R.TASKS), k),
                "length": np.full(len(seqs), 4096), "expected": np.asarray(["1234567"] * len(seqs))}
    return Frozen(public={"dev_prompts.npz": fake(2)}, hidden=fake(2), sources_sha256={"synthetic": f"n{n}"})
