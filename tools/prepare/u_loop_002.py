"""U-LOOP-002: synthetic held-out set (no download). 512 problems per task (pointer, reach, arith), difficulties
uniform, generated with a secret seed by the generator the agent sees (cases/U-LOOP-002/harness/reason_tasks.py).
There is no public data file."""
from __future__ import annotations

import importlib.util
import os
import sys
from pathlib import Path

from prepare.common import Frozen

HARNESS = Path(__file__).resolve().parents[2] / "cases" / "U-LOOP-002" / "harness"
SECRET_SEED_ENV = "ABENCH_U_LOOP2_SEED"          # escrowed by tools/prepare/run.py next to the hidden-set key
SOURCES = [{"name": "synthetic reasoning tasks", "generator": "cases/U-LOOP-002/harness/reason_tasks.py",
            "license": "generated by ABench"}]


def _stages():
    sys.path.insert(0, str(HARNESS))
    spec = importlib.util.spec_from_file_location("u_loop2_stages", HARNESS / "stages.py")
    mod = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(mod)
    return mod


def build(raw: Path) -> Frozen:
    seed = int(os.environ.get(SECRET_SEED_ENV, "0"))
    if not seed:
        raise SystemExit(f"set {SECRET_SEED_ENV} to a secret integer (the generator seed of the held-out set)")
    st = _stages()
    return Frozen(public={}, hidden=st.build_split(seed, st.PER_TASK),
                  sources_sha256={"generator": "reason_tasks.py", "seed": "secret (operator)"})


def synthetic(n: int) -> Frozen:
    st = _stages()
    return Frozen(public={}, hidden=st.build_split(7, max(8, min(n, 64))), sources_sha256={"synthetic": f"n{n}"})
