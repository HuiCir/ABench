"""PH-SYM-005: synthetic held-out set (no download). 20 dynamical systems drawn by the generator the agent sees
(cases/PH-SYM-005/harness/systems.py) with a secret seed: 11 known families with random parameters, variable order and
scales, and 9 random sparse polynomial systems. There is no public data file."""
from __future__ import annotations

import importlib.util
import os
import sys
from pathlib import Path

from prepare.common import Frozen

HARNESS = Path(__file__).resolve().parents[2] / "cases" / "PH-SYM-005" / "harness"
SECRET_SEED_ENV = "ABENCH_PH_SYM_SEED"          # escrowed by tools/prepare/run.py next to the hidden-set key

SOURCES = [{"name": "simulated dynamical systems", "generator": "cases/PH-SYM-005/harness/systems.py",
            "license": "generated by ABench"}]


def _stages():
    sys.path.insert(0, str(HARNESS))
    spec = importlib.util.spec_from_file_location("ph_sym_stages", HARNESS / "stages.py")
    mod = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(mod)
    return mod


def _frozen(seed: int, n: int, tag: dict) -> Frozen:
    st = _stages()
    import systems as S
    pre, ref = st.pack(S.sample_set(seed, n))
    return Frozen(public={}, hidden={**pre, **ref}, sources_sha256=tag)


def build(raw: Path) -> Frozen:
    seed = int(os.environ.get(SECRET_SEED_ENV, "0"))
    if not seed:
        raise SystemExit(f"set {SECRET_SEED_ENV} to a secret integer (the generator seed of the held-out systems)")
    return _frozen(seed, 20, {"generator": "systems.py", "seed": "secret (operator)"})


def synthetic(n: int) -> Frozen:
    return _frozen(7, 4, {"synthetic": f"n{n}"})
