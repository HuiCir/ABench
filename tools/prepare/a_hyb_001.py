"""A-HYB-001: the language-model data of B-OPT-001 (FineWeb-10B GPT-2 token shards, kjj0/fineweb10B-gpt2, MIT; train
shards 1-2 in the sandbox, the first 4,194,305 tokens of fineweb_val_000000.bin held out) plus held-out MQAR sequences
generated with a secret seed by cases/A-HYB-001/harness/mqar.py (A-LIN-002's generator) on a grid of longer sequences
and more key-value pairs than in training."""
from __future__ import annotations

import importlib.util
import os
import sys
from pathlib import Path

from prepare import b_opt_001
from prepare.common import Frozen

HARNESS = Path(__file__).resolve().parents[2] / "cases" / "A-HYB-001" / "harness"
SECRET_SEED_ENV = "ABENCH_A_HYB_SEED"          # escrowed by tools/prepare/run.py next to the hidden-set key
SOURCES = b_opt_001.SOURCES + [{"name": "MQAR (Arora et al. 2023, arXiv:2312.04927)",
                                "generator": "cases/A-HYB-001/harness/mqar.py", "license": "generated by ABench"}]
GRID = [(256, 16), (512, 32), (512, 64), (1024, 64), (1024, 128), (2048, 128), (2048, 256)]
PER_CELL = 256


def _stages():
    sys.path.insert(0, str(HARNESS))
    spec = importlib.util.spec_from_file_location("a_hyb_stages", HARNESS / "stages.py")
    mod = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(mod)
    return mod


def build(raw: Path) -> Frozen:
    seed = int(os.environ.get(SECRET_SEED_ENV, "0"))
    if not seed:
        raise SystemExit(f"set {SECRET_SEED_ENV} to a secret integer (the MQAR generator seed)")
    fz = b_opt_001.build(raw)
    fz.hidden.update(_stages().build_mqar_split(seed, GRID, PER_CELL))
    fz.sources_sha256["mqar"] = "generator mqar.py, seed secret (operator)"
    return fz


def synthetic(n: int) -> Frozen:
    fz = b_opt_001.synthetic(n)
    fz.hidden.update(_stages().build_mqar_split(1, GRID[:3], 4))
    return fz
