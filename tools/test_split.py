#!/usr/bin/env python3
"""Write TESTING.md: the testing work split by area (spec/areas.yaml), one section per area with every case's mode,
hardware, data source, current verification state and next step (verify.csv), so that each area can be handed to one
person or team.

  python3 tools/test_split.py           # write TESTING.md
  python3 tools/test_split.py --check   # exit 1 if TESTING.md is out of date
"""
from __future__ import annotations

import argparse
import csv
import sys
from collections import Counter
from pathlib import Path

import yaml
from catalog import load_catalog

ROOT = Path(__file__).resolve().parents[1]
OUT = ROOT / "TESTING.md"
REFRUN = {"real_gpu": "real data (GPU)", "real_cpu": "real data (CPU)", "synthetic": "synthetic data", "mock": "parts (mock)",
          "none": "not run"}
HW = {"cpu": "8 CPU cores", "gpu": "1 x 24GB GPU", "4xH100": "4 x H100"}


def cell(s: str, n: int = 160) -> str:
    s = " ".join(str(s or "").split()).replace("|", "/")
    return s if len(s) <= n else s[: n - 1] + "…"


def render() -> str:
    areas = yaml.safe_load((ROOT / "spec" / "areas.yaml").read_text(encoding="utf-8"))["areas"]
    reg = {r["case_id"]: r for r in csv.DictReader(open(ROOT / "verify.csv", newline="", encoding="utf-8"))}
    idx = yaml.safe_load((ROOT / "index.yaml").read_text(encoding="utf-8"))
    anchor = {c["id"]: c.get("anchor", "") for c in load_catalog(ROOT)}
    out = ["# Testing split", "",
           "Generated by `python3 tools/test_split.py` from `spec/areas.yaml` and `verify.csv`; edit those, not this file.",
           "",
           "Each part can be handed to one person or team. Testing a case means: download and freeze its real data "
           "(`python3 tools/prepare/run.py --case ID --list-sources`, then `--raw-dir`; data source `generated`: no "
           "download), run its OJ calibration on the case's hardware on that frozen data (`./abench calibrate ID`, `--gpus N` on a GPU: "
           "trains the reference submission where the case is a checkpoint case and judges it on the held-out split; "
           "data frozen with `--synthetic N` first is a quick plumbing check), check that the "
           "reference scores at the base with a sensible interval, and record the result in `verify.csv` "
           "(`ref_run` real_cpu / real_gpu, `ref_result`, `data_frozen`, `blockers`, `next_step`). The Pro Set is "
           "verified by its own audit on 4 x H100 (`spec/pro_set.md`). Questions about a case's design go to its spec "
           "(`spec/standard_cases/` or `spec/cases/`).", "",
           "| Part | Cases | Sub-areas | Hardware |", "|---|---|---|---|"]
    for a in areas:
        cases = [c for sa in a["subareas"] for c in sa["cases"]]
        hw = Counter(reg[c]["device"] for c in cases)
        out.append(f"| {a['name']} (`{a['id']}`) | {len(cases)} | {', '.join(sa['id'] for sa in a['subareas'])} | "
                   + ", ".join(f"{HW.get(k, k)} × {n}" for k, n in sorted(hw.items())) + " |")
    for a in areas:
        cases = [c for sa in a["subareas"] for c in sa["cases"]]
        st = Counter(reg[c]["ref_run"] for c in cases)
        out += ["", f"## {a['name']} (`{a['id']}`, {len(cases)} cases)", "",
                "Reference runs so far: " + ", ".join(f"{REFRUN.get(k, k)} {n}" for k, n in sorted(st.items())) + "."]
        for sa in a["subareas"]:
            out += ["", f"### {sa['name']} (`{sa['id']}`)", "",
                    "| Case | Anchor | Mode | Hardware | Data | Reference run | Next step / blockers |",
                    "|---|---|---|---|---|---|---|"]
            for c in sa["cases"]:
                r = reg[c]
                nxt = r["next_step"] + (f" — blockers: {r['blockers']}" if r["blockers"].strip() else "")
                tag = " (calibration case)" if r["review_tier"] == "cal" else ""
                out.append(f"| {c}{tag} | {cell(anchor.get(c), 48)} | {r['mode']} | {HW.get(r['device'], r['device'])} | "
                           f"{r['data_source']} | {REFRUN.get(r['ref_run'], r['ref_run'])} | {cell(nxt)} |")
    return "\n".join(out) + "\n"


def main() -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument("--check", action="store_true")
    a = ap.parse_args()
    text = render()
    if a.check:
        ok = OUT.is_file() and OUT.read_text(encoding="utf-8") == text
        print("TESTING.md " + ("up to date" if ok else "out of date (python3 tools/test_split.py)"))
        return 0 if ok else 1
    OUT.write_text(text, encoding="utf-8")
    print("wrote", OUT)
    return 0


if __name__ == "__main__":
    sys.exit(main())
