"""Split the micro fixture of DS-GBM-001 into an OJ-style public training set and an encrypted hidden set.

  Public: sandbox/data/DS-GBM-001/train.npz   (x, y; visible to the agent)
  Hidden: sandbox/hidden/DS-GBM-001/test.npz.enc (x, y; only the judge can decrypt)

and write the file hashes back to cases/DS-GBM-001/case/oj.yaml. The source fixture is synthetic data generated by build_data(seed=17) in the old smoke script (moved to _to_delete/legacy_v1/tools/smoke_ds_gbm.py)
(12-dimensional Gaussian features, binary classification), used only to validate the pipeline and not representative of the formal data.

Usage: python3 tools/prepare_ds_gbm_micro.py --key-file <hidden.key>
"""
from __future__ import annotations

import argparse
import hashlib
import io
from pathlib import Path

import numpy as np
import yaml

import hidden_store

ROOT = Path(__file__).resolve().parents[1]


def npz_bytes(**arrays) -> bytes:
    buf = io.BytesIO()
    np.savez(buf, **arrays)
    return buf.getvalue()


def main() -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument("--key-file", required=True)
    ap.add_argument("--fixture", default=str(ROOT / "sandbox/fixtures/ds_gbm_micro_v1.npz"))
    a = ap.parse_args()
    with np.load(a.fixture, allow_pickle=False) as z:
        tx, ty, vx, vy = z["train_x"], z["train_y"], z["test_x"], z["test_y"]
    pub = ROOT / "sandbox/data/DS-GBM-001/train.npz"
    hid = ROOT / "sandbox/hidden/DS-GBM-001/test.npz.enc"
    pub.parent.mkdir(parents=True, exist_ok=True); hid.parent.mkdir(parents=True, exist_ok=True)
    pub_b = npz_bytes(x=tx.astype(np.float32), y=ty.astype(np.int64))
    pub.write_bytes(pub_b)
    hid_plain = npz_bytes(x=vx.astype(np.float32), y=vy.astype(np.int64))
    hid.write_bytes(hidden_store.encrypt_bytes(hidden_store.read_key(Path(a.key_file)), hid_plain))
    # Ciphertext is not sufficient to recover labels without the key, but keep
    # the hidden artifact operator-only so accidental copies cannot be treated
    # as public case data or mounted into an agent view.
    hid.chmod(0o600)

    oj_path = ROOT / "cases/DS-GBM-001/case/oj.yaml"
    oj = yaml.safe_load(oj_path.read_text(encoding="utf-8"))
    oj["data"]["public"][0].update(path=str(pub.relative_to(ROOT)), sha256=hashlib.sha256(pub_b).hexdigest(),
                                   rows=int(len(ty)))
    oj["data"]["hidden"].update(path=str(hid.relative_to(ROOT)), sha256_plain=hashlib.sha256(hid_plain).hexdigest(),
                                rows=int(len(vy)))
    oj_path.write_text(yaml.safe_dump(oj, allow_unicode=True, sort_keys=False), encoding="utf-8")
    print("public", pub, len(ty), "rows; hidden", hid, len(vy), "rows (encrypted)")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
