"""verify.csv: one row per case in index.yaml recording how far its design and verification have got.

Maintained by hand and by this tool. Columns marked (derived) are recomputed from the repository by --sync and
checked by --check; the other columns are the operator's record and are only validated.

  case_id, track, group, type, budget            (derived from index.yaml)
  area, subarea   (derived) the testing and ownership split of spec/areas.yaml
  design          (derived) none | designed       spec/cases/<ID>.yaml, spec/standard_cases/<ID>.yaml or a handcrafted oj.yaml
  mode            (derived) checkpoint | judge_trains | no_training | timed_train | judgment | - (from the spec or oj.yaml)
  device          (derived) cpu | gpu | 4xH100
  harness         (derived) yes | no            cases/<ID>/harness/stages.py and metrics.py (or the handcrafted judge)
  prepare         (derived) yes | no            tools/prepare/<id>.py (or tools/prepare_<x>.py for handcrafted cases)
  secret_seed     (derived) yes | no            the prepare module declares SECRET_SEED_ENV (seed escrow needed at freeze)
  data_source     public_verified | operator_download | generated | blocked | -
                  public_verified: every source pinned (revision, licence) and its metadata checked (API, clone or hash);
                                   whether the files can be fetched from the build environment is noted under blockers
                  operator_download: pinned, but not yet checked; the operator fetches and verifies it at freeze
  ref_run         none | mock | synthetic | real_cpu | real_gpu    the furthest the reference submission has run
  ref_result      free text: the calibration numbers (required for real_cpu / real_gpu)
  baseline_tuned  n/a | pending | done          for cases whose baseline must be tuned before activation
  data_frozen     no | <YYYY-MM-DD>             tools/prepare/run.py has frozen public and hidden data
  hidden_escrow   n/a | pending | done          secret seed escrowed next to the key (cases with secret_seed = yes)
  activation      not_designed | awaiting_data | judge_pending | active
  review_tier     - | cal | 1 | 2 | 3      quality review of the case (2026-10-23 onward):
                  cal: pipeline-calibration case (index scope: calibration); kept to calibrate the judge and runner,
                     not part of the scored set
                  1: task design reviewed and accepted; data and models pinned from metadata (API, card, checksum
                     list) but their contents not yet read
                  2: as 1, and every data file the case uses has been read or generated by a checked generator,
                     every model is pinned with revision and licence
                  3: needs rework, or the research question is weak or duplicated (review_note says which)
  review_note     free text (required for tier 3)
  last_update     YYYY-MM-DD
  blockers, next_step   free text

Usage:
  python3 tools/verify_registry.py --check     # validate; exit 1 on any inconsistency
  python3 tools/verify_registry.py --sync      # add rows for new index cases, drop removed ones, refresh derived columns
  python3 tools/verify_registry.py --summary   # counts per stage and per area
"""
from __future__ import annotations

import argparse
import csv
import re
import sys
from collections import Counter
from pathlib import Path

import yaml

ROOT = Path(__file__).resolve().parents[1]
CSV = ROOT / "verify.csv"
COLS = ["case_id", "track", "group", "area", "subarea", "type", "budget", "design", "mode", "device", "harness", "prepare", "secret_seed",
        "data_source", "ref_run", "ref_result", "baseline_tuned", "data_frozen", "hidden_escrow", "activation",
        "review_tier", "review_note", "last_update", "blockers", "next_step"]
DERIVED = ["track", "group", "area", "subarea", "type", "budget", "design", "mode", "device", "harness", "prepare", "secret_seed"]
ENUM = {"design": {"none", "designed"}, "harness": {"yes", "no"}, "prepare": {"yes", "no"}, "secret_seed": {"yes", "no"},
        "data_source": {"public_verified", "operator_download", "generated", "blocked", "-"},
        "ref_run": {"none", "mock", "synthetic", "real_cpu", "real_gpu"},
        "baseline_tuned": {"n/a", "pending", "done"}, "hidden_escrow": {"n/a", "pending", "done"},
        "activation": {"not_designed", "awaiting_data", "judge_pending", "active"},
        "review_tier": {"-", "cal", "1", "2", "3"}}
DATE = re.compile(r"^\d{4}-\d{2}-\d{2}$")
HANDCRAFTED_PREPARE = {"IC-SPD-001": "tools/prepare_ic_spd.py"}


def area_of() -> dict:
    """case id -> (area id, subarea id) from spec/areas.yaml."""
    p = ROOT / "spec" / "areas.yaml"
    if not p.is_file():
        return {}
    out = {}
    for a in yaml.safe_load(p.read_text(encoding="utf-8"))["areas"]:
        for sa in a["subareas"]:
            for cid in sa["cases"]:
                out[cid] = (a["id"], sa["id"])
    return out


AREAS = area_of()


def index_cases() -> list[tuple[dict, dict]]:
    idx = yaml.safe_load((ROOT / "index.yaml").read_text(encoding="utf-8"))
    return [(t, c) for t in idx["tracks"] for c in t["cases"]]


def spec_of(cid: str) -> dict | None:
    for d in ("cases", "standard_cases", "handcrafted"):
        p = ROOT / "spec" / d / f"{cid}.yaml"
        if p.is_file():
            return yaml.safe_load(p.read_text(encoding="utf-8"))
    return None


def oj_of(cid: str) -> dict:
    p = ROOT / "cases" / cid / "case" / "oj.yaml"
    return (yaml.safe_load(p.read_text(encoding="utf-8")) or {}) if p.is_file() else {}


def derived(track: dict, c: dict) -> dict:
    cid = c["id"]
    s, oj = spec_of(cid), oj_of(cid)
    handcrafted = bool(oj.get("handcrafted")) and (oj.get("judge") or {}).get("kind") not in (None, "pending")
    designed = s is not None or handcrafted
    mode = (s or {}).get("mode") or ((oj.get("judge") or {}).get("kind") if handcrafted else None) or "-"
    if cid.startswith("PRO-"):
        device = "4xH100"
    else:
        kind = ((s or {}).get("hardware") or {}).get("kind")
        dev = ((oj.get("judge") or {}).get("device") or "")
        device = "cpu" if (kind == "cpu" or (kind is None and dev == "cpu")) else "gpu"
    h = ROOT / "cases" / cid / "harness"
    harness = "yes" if ((h / "stages.py").is_file() and (h / "metrics.py").is_file()) or handcrafted else "no"
    mod = ROOT / "tools" / "prepare" / (cid.lower().replace("-", "_") + ".py")
    if cid in HANDCRAFTED_PREPARE:
        mod = ROOT / HANDCRAFTED_PREPARE[cid]
    prepare = "yes" if mod.is_file() else "no"
    seed = "yes" if prepare == "yes" and "SECRET_SEED_ENV" in mod.read_text(encoding="utf-8") else "no"
    area, sub = AREAS.get(cid, ("-", "-"))
    return {"track": track["id"], "group": track.get("group", ""), "area": area, "subarea": sub, "type": c.get("type", ""), "budget": c.get("budget", ""),
            "design": "designed" if designed else "none", "mode": mode, "device": device, "harness": harness,
            "prepare": prepare, "secret_seed": seed}


def read(allow_new_columns: bool = False) -> list[dict]:
    with open(CSV, newline="", encoding="utf-8") as f:
        r = csv.DictReader(f)
        if r.fieldnames != COLS:
            if not (allow_new_columns and set(r.fieldnames or []) <= set(COLS)):
                raise SystemExit(f"verify.csv columns differ from {COLS} (run --sync)")
        return [{k: row.get(k, "") or "" for k in COLS} for row in r]


def write(rows: list[dict]) -> None:
    with open(CSV, "w", newline="", encoding="utf-8") as f:
        w = csv.DictWriter(f, fieldnames=COLS, lineterminator="\n")
        w.writeheader()
        w.writerows(rows)


def check(rows: list[dict]) -> list[str]:
    errs = []
    cases = index_cases()
    ids = [c["id"] for _, c in cases]
    got = [r["case_id"] for r in rows]
    if sorted(got) != sorted(ids):
        errs.append(f"rows differ from index.yaml: missing {sorted(set(ids) - set(got))}, extra {sorted(set(got) - set(ids))}")
    if len(got) != len(set(got)):
        errs.append("duplicate case_id rows")
    by = {r["case_id"]: r for r in rows}
    for t, c in cases:
        r = by.get(c["id"])
        if r is None:
            continue
        cid = c["id"]
        for k, v in derived(t, c).items():
            if r[k] != v:
                errs.append(f"{cid}: {k} = {r[k]!r}, repository says {v!r} (run --sync)")
        for k, allowed in ENUM.items():
            if r[k] not in allowed:
                errs.append(f"{cid}: {k} = {r[k]!r} not in {sorted(allowed)}")
        if r["ref_run"] in ("real_cpu", "real_gpu") and not r["ref_result"].strip():
            errs.append(f"{cid}: ref_run {r['ref_run']} needs ref_result")
        if r["data_frozen"] != "no" and not DATE.match(r["data_frozen"]):
            errs.append(f"{cid}: data_frozen must be no or a date")
        if not DATE.match(r["last_update"]):
            errs.append(f"{cid}: last_update must be YYYY-MM-DD")
        if r["secret_seed"] == "yes" and r["hidden_escrow"] == "n/a":
            errs.append(f"{cid}: secret_seed yes needs hidden_escrow pending or done")
        if r["secret_seed"] == "no" and r["hidden_escrow"] != "n/a":
            errs.append(f"{cid}: hidden_escrow must be n/a without a secret seed")
        if r["design"] == "none" and r["activation"] != "not_designed":
            errs.append(f"{cid}: undesigned case must have activation not_designed")
        if r["design"] == "designed" and r["activation"] == "not_designed":
            errs.append(f"{cid}: designed case cannot be not_designed")
        if r["activation"] == "active" and (r["data_frozen"] == "no" or r["ref_run"] not in ("real_cpu", "real_gpu")
                                            or r["hidden_escrow"] == "pending" or r["baseline_tuned"] == "pending"):
            errs.append(f"{cid}: active requires frozen data, a real reference run, escrowed seed and tuned baseline")
        if r["review_tier"] == "3" and not r["review_note"].strip():
            errs.append(f"{cid}: review tier 3 needs a review_note")
        if r["activation"] == "active" and r["review_tier"] not in ("1", "2"):
            errs.append(f"{cid}: active requires review tier 1 or 2")
        if r["design"] == "designed" and not r["next_step"].strip() and r["activation"] != "active":
            errs.append(f"{cid}: next_step is empty")
    from catalog import load_catalog, catalog_errors
    try:
        errs.extend(catalog_errors(load_catalog(ROOT), ROOT))
    except (ValueError, KeyError, OSError) as error:
        errs.append(f"catalog: {error}")
    return errs


def sync(rows: list[dict]) -> list[dict]:
    by = {r["case_id"]: r for r in rows}
    out = []
    for t, c in index_cases():
        r = by.get(c["id"]) or {k: "" for k in COLS}
        r["case_id"] = c["id"]
        r.update(derived(t, c))
        defaults = {"data_source": "-", "ref_run": "none", "baseline_tuned": "n/a", "data_frozen": "no", "review_tier": "-",
                    "hidden_escrow": "pending" if r["secret_seed"] == "yes" else "n/a",
                    "activation": "awaiting_data" if r["design"] == "designed" else "not_designed"}
        for k, v in defaults.items():
            if not r.get(k):
                r[k] = v
        if r["design"] == "designed" and r["activation"] == "not_designed":
            r["activation"] = "awaiting_data"
        if r["design"] == "none":
            r["activation"] = "not_designed"
        if r["secret_seed"] == "no":
            r["hidden_escrow"] = "n/a"
        elif r["hidden_escrow"] == "n/a":
            r["hidden_escrow"] = "pending"
        out.append(r)
    dropped = sorted(set(by) - {r["case_id"] for r in out})
    if dropped:
        print("dropped rows (no longer in index.yaml):", ", ".join(dropped))
    return out


def summary(rows: list[dict]) -> None:
    print(f"{len(rows)} cases")
    for k in ("area", "subarea", "design", "review_tier", "ref_run", "activation", "data_source", "device"):
        print(f"  {k}: " + ", ".join(f"{v} {n}" for v, n in sorted(Counter(r[k] for r in rows).items())))


def main() -> int:
    ap = argparse.ArgumentParser()
    g = ap.add_mutually_exclusive_group(required=True)
    g.add_argument("--check", action="store_true")
    g.add_argument("--sync", action="store_true")
    g.add_argument("--summary", action="store_true")
    a = ap.parse_args()
    rows = read(allow_new_columns=a.sync) if CSV.is_file() else []
    if a.sync:
        rows = sync(rows)
        write(rows)
    if a.summary:
        summary(rows)
        return 0
    errs = check(rows)
    for e in errs:
        print("ERROR", e)
    print(f"verify.csv: {len(rows)} rows, {len(errs)} error(s)")
    return 1 if errs else 0


if __name__ == "__main__":
    sys.exit(main())
